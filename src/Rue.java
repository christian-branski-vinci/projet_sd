public class Rue {

  double distance;
  String nom;

  public Rue(double distance, String nom) {
    this.distance = distance;
    this.nom = nom;
  }

  public double getDistance() {
    return distance;
  }

  public void setDistance(double distance) {
    this.distance = distance;
  }

  public String getNom() {
    return nom;
  }

  public void setNom(String nom) {
    this.nom = nom;
  }

}
